/** Percent-encode each path segment so odd file names stay valid relative links. */
function href(name: string): string {
  return encodeURI(name).replace(/#/g, "%23").replace(/\?/g, "%3F");
}

export function renderIndexHtml(index: ReportIndex, opts: { lang?: HtmlLang; gdlVersion: string }): string {
  const t = opts.lang === "zh-TW" ? ZH_I : EN_I;
  const rows = index.entries.map((e) => {
    const links = [`<a href="${href(e.file)}">${t.json}</a>`, ...(e.html ? [`<a href="${href(e.html)}">${t.html}</a>`] : [])].join(" · ");
    const model = `<span title="${esc(e.modelSha256)}">${esc(e.modelSha256.slice(0, 10))}</span>`;
    return `<tr><td>${esc(e.generatedAt)}</td><td>${esc(e.kind)}${e.scenarios !== null ? ` <small>${e.scenarios} sc.</small>` : ""}${e.valid ? "" : " " + badge("critical", t.invalid)}</td><td>${esc(e.project)}</td><td>${e.policy ? `${esc(e.policy)} · ${esc(e.mode ?? "")}` : "-"}</td><td class="n">${e.runs ?? "-"}</td><td class="n">${e.completionRate === null ? "-" : pct(e.completionRate)}</td><td class="n">${e.medianMinutes === null ? "-" : fmtMin(e.medianMinutes)}</td><td class="n">${e.findings.critical > 0 ? `<b class="bad">${e.findings.critical}</b>` : "0"}/${e.findings.warning > 0 ? `<b class="warn">${e.findings.warning}</b>` : "0"}/${e.findings.info}</td><td>${model}</td><td>${links}</td></tr>`;
  });
  const table = index.entries.length
    ? `<table><thead><tr><th>${t.thWhen}</th><th>${t.thKind}</th><th>${t.thProject}</th><th>${t.thPolicy}</th><th>${t.thRuns}</th><th>${t.thCompl}</th><th>${t.thMedian}</th><th>${esc(t.thFindings)}</th><th>${t.thModel}</th><th>${t.thOpen}</th></tr></thead><tbody>${rows.join("")}</tbody></table>`
    : `<p class="muted">${esc(t.empty)}</p>`;
  const skipped = index.skipped.length ? `<h3>${esc(t.skippedH)}</h3><ul>${index.skipped.map((s) => `<li><code>${esc(s.file)}</code> — ${esc(s.reason)}</li>`).join("")}</ul>` : "";
  return `<!doctype html>
<html lang="${opts.lang === "zh-TW" ? "zh-Hant" : "en"}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="GDL ${esc(opts.gdlVersion)}">
<title>GDL ${esc(t.title)}</title>
<style>${CSS}</style>
</head>
<body>
<header>
  <div class="title"><h1>GDL ${esc(t.title)}</h1><span class="kind">${index.entries.length}</span></div>
  <p class="muted">${esc(t.hint)}</p>
</header>
<main>
<section>${table}${skipped}</section>
</main>
<footer><p class="muted">${esc(t.footer(opts.gdlVersion))}</p></footer>
<script type="application/json" id="gdl-index">${embedJson({ entries: index.entries, skipped: index.skipped })}</script>
</body>
</html>
`;
}

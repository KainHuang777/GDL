/**
 * Static index of saved reports in a directory (docs/dashboard-design.md §8).
 * Lists every readable GDL report JSON (newest first) with headline numbers and a link
 * to the sibling `.html` dashboard when it exists. Unreadable files are listed, not fatal.
 */

export interface IndexEntry {
  /** File name relative to the index directory. */
  file: string;
  html: string | null;
  kind: AnyReport["kind"];
  project: string;
  generatedAt: string;
  modelSha256: string;
  valid: boolean;
  policy: string | null;
  mode: string | null;
  runs: number | null;
  completionRate: number | null;
  medianMinutes: number | null;
  scenarios: number | null;
  findings: { critical: number; warning: number; info: number };
}

export interface ReportIndex {
  dir: string;
  entries: IndexEntry[];
  skipped: { file: string; reason: string }[];
}

export const INDEX_FILE = "index.html";

export async function buildReportIndex(dir: string, insightsFor: (r: AnyReport) => Insights | Promise<Insights>): Promise<ReportIndex> {
  const abs = path.resolve(dir);
  const names = (await fs.readdir(abs).catch(() => [] as string[])).filter((n) => n.toLowerCase().endsWith(".json")).sort();
  const entries: IndexEntry[] = [];
  const skipped: ReportIndex["skipped"] = [];
  for (const name of names) {
    let report: AnyReport;
    try {
      report = await readReport(path.join(abs, name));
    } catch (e) {
      skipped.push({ file: name, reason: (e as Error).message.replace(/^.*?: /, "") });
      continue;
    }
    const ins = await insightsFor(report);
    const f = { critical: 0, warning: 0, info: 0 };
    for (const x of ins.findings) f[x.severity]++;
    const sim: SimulationResult | undefined = report.kind === "compare" ? report.baseline : report.kind === "validate" ? undefined : report.simulation;
    const htmlName = name.replace(/\.json$/i, ".html");
    const hasHtml = await fs.stat(path.join(abs, htmlName)).then((s) => s.isFile(), () => false);
    entries.push({
      file: name,
      html: hasHtml ? htmlName : null,
      kind: report.kind,
      project: report.provenance.project.id,
      generatedAt: report.provenance.generatedAt,
      modelSha256: report.provenance.modelSha256,
      valid: report.validation.ok,
      policy: sim?.policy.id ?? null,
      mode: sim?.mode ?? null,
      runs: sim?.runs ?? null,
      completionRate: sim?.completionRate ?? null,
      medianMinutes: sim?.minutes.median ?? null,
      scenarios: report.kind === "compare" ? report.scenarios.length : null,
      findings: f,
    });
  }
  entries.sort((a, b) => b.generatedAt.localeCompare(a.generatedAt) || a.file.localeCompare(b.file));
  return { dir: abs, entries, skipped };
}

